export function ensureInkDefs(doc = globalThis.document) {
  if (!doc || doc.getElementById('ink-rough')) return;
  doc.body.insertAdjacentHTML('afterbegin', INK_DEFS);
}

export function inkIcon(name, {size = 24, label} = {}) {
  const parts = INK_ICONS[name];
  if (!parts) return '';
  let ink = '', seal = '';
  for (const part of parts) {
    const d = part.dot ? dab(part.dot) : strokePath(part);
    if (part.seal) seal += d; else ink += d;
  }
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"';
  return `<svg class="ink-icon" viewBox="0 0 24 24" width="${size}" height="${size}" ${a11y}><g filter="url(#ink-rough)">`
    + `<path d="${ink}" fill="currentColor"/>` + (seal ? `<path d="${seal}" fill="var(--cinnabar,#a63a2b)"/>` : '') + '</g></svg>';
}
