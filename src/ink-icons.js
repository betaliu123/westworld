function curve(points, steps = 10) {
  if (points.length < 3) {
    const [a, b] = points, out = [];
    for (let i = 0; i <= steps; i++) { const t = i / steps; out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]); }
    return out;
  }
  const out = [], p = i => points[Math.max(0, Math.min(points.length - 1, i))];
  for (let i = 0; i < points.length - 1; i++) {
    const [p0, p1, p2, p3] = [p(i - 1), p(i), p(i + 1), p(i + 2)];
    for (let s = 0; s < steps; s++) {
      const t = s / steps, t2 = t * t, t3 = t2 * t;
      out.push([0, 1].map(k => .5 * (2 * p1[k] + (-p0[k] + p2[k]) * t + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t2 + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t3)));
    }
  }
  out.push(points[points.length - 1]);
  return out;
}

const pressure = t => t < .12 ? .62 + .38 * t / .12 : 1 - .55 * ((t - .12) / .88) ** 1.4;
const f = n => +n.toFixed(2);

function strokePath({w, points}) {
  const line = curve(points), left = [], right = [];
  let total = 0; const lengths = [0];
  for (let i = 1; i < line.length; i++) lengths.push(total += Math.hypot(line[i][0] - line[i - 1][0], line[i][1] - line[i - 1][1]));
  line.forEach(([x, y], i) => {
    const a = line[Math.max(0, i - 1)], b = line[Math.min(line.length - 1, i + 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1, half = w * pressure(lengths[i] / (total || 1)) / 2;
    left.push([x - dy / len * half, y + dx / len * half]); right.push([x + dy / len * half, y - dx / len * half]);
  });
  const r = w * .62 / 2, [sx, sy] = line[0];
  const body = 'M' + left.map(p => p.map(f).join(' ')).join('L') + 'L' + right.reverse().map(p => p.map(f).join(' ')).join('L') + 'Z';
  return body + `M${f(sx - r)} ${f(sy)}a${f(r)} ${f(r)} 0 1 0 ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-2 * r)} 0Z`;
}

const dab = ([x, y, r]) => `M${f(x - r)} ${f(y)}a${f(r)} ${f(r * .86)} -20 1 0 ${f(2 * r)} 0a${f(r)} ${f(r * .86)} -20 1 0 ${f(-2 * r)} 0Z`;

