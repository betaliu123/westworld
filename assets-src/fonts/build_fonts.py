"""Subset the OFL source fonts in this folder into vendor/fonts/*.woff2.

Run from anywhere:  python assets-src/fonts/build_fonts.py
Re-run after adding new UI text so the "core" slices pick up new characters.
"""
import re, shutil
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / 'vendor' / 'fonts'
CJK = re.compile(r'[\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uff00-\uffef\u2010-\u2027\u00b7]')
ASCII = ''.join(chr(c) for c in range(0x20, 0x7f))

# Display (title) strings that come from code paths rather than literals, plus result glyphs.
DATA_CHARS = '０１２３４５６７８９＋－×÷％·／：一二三四五六七八九十百千两文日时刻次成败险'
TITLE_EXTRA = '江湖有回声临溪镇关县狱茶棚绛云楼北街城门东西南北成败险胜负平生死逃擒醉毒伤愈入城出狱章壹贰叁肆伍陆柒捌玖拾初入江湖记事出狱了翻墙赵更生宣旧纸焦浓重淡清墨朱砂石绿赭青释行商'
TITLE_EXTRA += '三日后'


def project_text():
    text = []
    for pattern in ('src/**/*.js', 'index.html', 'style.css', 'docs/美术视觉与界面规范.md', 'cc_task/2026-11-10-ui/*.html'):
        for f in ROOT.glob(pattern):
            text.append(f.read_text(encoding='utf-8', errors='ignore'))
    return ''.join(text)


def gb2312_level1():
    chars = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return ''.join(chars)


def unicodes(chars):
    return sorted({ord(c) for c in chars})


def ranges(points):
    """Compact unicode-range string for @font-face."""
    out, start, prev = [], None, None
    for p in points:
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append((start, prev)); start = prev = p
    if start is not None:
        out.append((start, prev))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def write(font_path, points, name, font=None):
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    font = font or TTFont(font_path)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=points)
    sub.subset(font)
    path = OUT / name
    font.flavor = 'woff2'
    font.save(path)
    print(f'{name:34s} {len(points):5d} glyphs {path.stat().st_size / 1024:8.0f} KB')
    return path


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    used = set(CJK.findall(project_text())) | set(ASCII)
    common = set(gb2312_level1()) | used
    core = unicodes(used)
    ext = unicodes(common - used)

    write(HERE / 'LXGWWenKai-Regular.ttf', core, 'wenkai-core.woff2')
    write(HERE / 'LXGWWenKai-Regular.ttf', ext, 'wenkai-ext.woff2')

    title = unicodes(set(TITLE_EXTRA) | set(ASCII) | set(CJK.findall(display_text())))
    write(HERE / 'ZhiMangXing-Regular.ttf', title, 'zhimangxing.woff2')
    write(HERE / 'MaShanZheng-Regular.ttf', title, 'mashanzheng.woff2')

    serif = instancer.instantiateVariableFont(TTFont(HERE / 'NotoSerifSC-VF.ttf'), {'wght': 600})
    data = unicodes(set(ASCII) | set(DATA_CHARS))
    write(None, data, 'notoserifsc-600.woff2', font=serif)

    for src, dst in (('ZhiMangXing-OFL.txt', 'OFL-ZhiMangXing.txt'), ('MaShanZheng-OFL.txt', 'OFL-MaShanZheng.txt'), ('LXGWWenKai-OFL.txt', 'OFL-LXGWWenKai.txt'), ('NotoSerifSC-OFL.txt', 'OFL-NotoSerifSC.txt')):
        if (HERE / src).exists():
            shutil.copy(HERE / src, OUT / dst)
    face = lambda family, file, rng=None, weight=400: (
        f"@font-face{{font-family:'{family}';src:url('{file}') format('woff2');font-weight:{weight};font-display:swap;"
        + (f"unicode-range:{rng};" if rng else '') + '}\n')
    (OUT / 'fonts.css').write_text(
        '/* Generated by assets-src/fonts/build_fonts.py. SIL OFL 1.1 fonts; licenses beside this file. */\n'
        + face('Jianghu Title', 'zhimangxing.woff2', ranges(title))
        + face('Jianghu Title Alt', 'mashanzheng.woff2', ranges(title))
        + face('Jianghu Body', 'wenkai-core.woff2', ranges(core))
        + face('Jianghu Body', 'wenkai-ext.woff2', ranges(ext))
        + face('Jianghu Data', 'notoserifsc-600.woff2', ranges(data), 600),
        encoding='utf-8')


def display_text():
    """Short display strings: names, places and headings that may be set in the title face."""
    text = []
    data = (ROOT / 'src' / 'data.js').read_text(encoding='utf-8', errors='ignore')
    text += re.findall(r"name\s*:\s*['\"]([^'\"]{1,8})['\"]", data)
    text += re.findall(r"title\s*:\s*['\"]([^'\"]{1,8})['\"]", data)
    world = (ROOT / 'src' / 'world.js').read_text(encoding='utf-8', errors='ignore')
    text += re.findall(r"this\.house\([^']*'([^']+)'", world)
    text += re.findall(r"textSprite\('([^']+)'", world)
    scenery = (ROOT / 'src' / 'location-scenery.js').read_text(encoding='utf-8', errors='ignore')
    text += re.findall(r"name\s*:\s*'([^']{1,8})'", scenery) + re.findall(r"textSprite\('([^']+)'", scenery)
    for f in ('locations.js', 'data.js'):
        p = ROOT / 'src' / f
        if p.exists():
            text += re.findall(r"(?:name|label|place)\s*:\s*'([^']{1,8})'", p.read_text(encoding='utf-8', errors='ignore'))
    for f in (ROOT / 'cc_task' / '2026-11-10-ui').glob('*.html'):
        text += re.findall(r'class="[^"]*\bt-title\b[^"]*"[^>]*>([^<]{1,16})<', f.read_text(encoding='utf-8'))
    return ''.join(text)


if __name__ == '__main__':
    main()
